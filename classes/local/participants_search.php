namespace report_fastparticipants\local;

use core_user\fields;

/**
 * Lean participants search used by the fast participants report.
 *
 * The query never uses DISTINCT nor derived tables. The only join is {user_lastaccess}, which is unique
 * per (userid, courseid), and every filter is a semijoin (u.id IN / NOT IN subquery), so each user appears
 * once no matter how many enrolments, roles or groups they have. The join is added only when a query needs it
 * (the last access filter is active, or the page is sorted by last access), because MySQL does not eliminate
 * unused outer joins:
 *
 *     FROM {user} u
 *     [LEFT JOIN {user_lastaccess} ul ON ul.userid = u.id AND ul.courseid = :course]
 *     WHERE u.deleted = 0 AND u.id <> :guest
 *       AND u.id IN (SELECT ue.userid FROM {user_enrolments} ue JOIN {enrol} e ... [forced active])
 *       AND u.id IN (...filter...) ...
 *
 * Counting, paging and loading the page users are separate queries, the latter only touching the page ids
 * (deferred join), so custom profile field joins never run against the whole course.
 *
 * @package    report_fastparticipants
 * @copyright  2026 Danilo Machado <danilo.alexandre182@gmail.com>
 * @license    http://www.gnu.org/copyleft/gpl.html GNU GPL v3 or later
 */
final class participants_search {
    /** Prefix of every named SQL parameter generated by this class. */
    private const PARAM_PREFIX = 'rfp';

    /** @var \stdClass The course. */
    private \stdClass $course;

    /** @var \context_course The course context. */
    private \context_course $context;

    /** @var filter The normalised filter. */
    private filter $filter;

    /** @var int Counter used to generate unique parameter names. */
    private int $paramcounter = 0;

    /** @var array|null Cached ['from' => string, 'where' => string, 'params' => array, 'join' => string, 'joinparams' => array]. */
    private ?array $basesql = null;

    /**
     * Constructor.
     *
     * @param \stdClass $course The course.
     * @param \context_course $context The course context.
     * @param filter $filter The filter; it is normalised here when the caller did not do it.
     */
    public function __construct(\stdClass $course, \context_course $context, filter $filter) {
        $this->course = $course;
        $this->context = $context;
        $this->filter = $filter->is_normalised() ? $filter : $filter->normalise($course, $context);
    }

    /**
     * Counts the users matching the filter.
     *
     * @return int
     */
    public function count(): int {
        global $DB;

        if ($this->filter->is_notingroup()) {
            return 0;
        }
        ['from' => $from, 'where' => $where, 'params' => $params] = $this->get_query_sql(
            $this->filter->get_accesssince() !== 0
        );
        return (int) $DB->count_records_sql("SELECT COUNT(1) FROM {$from} WHERE {$where}", $params);
    }

    /**
     * Returns the ids of the users of one page, in display order.
     *
     * @param array $sortcolumns column => SORT_ASC|SORT_DESC (as flexible_table::get_sort_columns()).
     * @param int $offset First row (0 based).
     * @param int $limit Number of rows.
     * @return int[]
     */
    public function get_page_userids(array $sortcolumns, int $offset, int $limit): array {
        global $DB;

        if ($this->filter->is_notingroup() || $limit <= 0) {
            return [];
        }
        $orderby = $this->get_order_by($sortcolumns);
        ['from' => $from, 'where' => $where, 'params' => $params] = $this->get_query_sql($this->needs_lastaccess_join($orderby));
        $rs = $DB->get_recordset_sql(
            "SELECT u.id FROM {$from} WHERE {$where} ORDER BY {$orderby}",
            $params,
            max(0, $offset),
            $limit
        );
        $ids = [];
        foreach ($rs as $record) {
            $ids[] = (int) $record->id;
        }
        $rs->close();
        return $ids;
    }

    /**
     * Loads the users to display (user picture fields, visible identity fields and course last access).
     *
     * Only the given ids are touched, so custom profile field joins stay cheap.
     *
     * @param int[] $userids User ids, usually the result of {@see self::get_page_userids()}.
     * @return \stdClass[] id => user, in the same order as $userids
     */
    public function get_users(array $userids): array {
        global $DB;

        $userids = array_values(array_unique(array_map('intval', $userids)));
        if (empty($userids)) {
            return [];
        }

        $userfields = fields::for_userpic()->with_identity($this->context, true)->get_sql('u', true, '', '', false);
        [$insql, $inparams] = $DB->get_in_or_equal($userids, SQL_PARAMS_NAMED, $this->next_param_name() . '_');
        $courseparam = $this->next_param_name();
        $ctxparam = $this->next_param_name();
        $ctxfields = \context_helper::get_preload_record_columns_sql('ctx');

        $sql = "SELECT {$userfields->selects}, COALESCE(ul.timeaccess, 0) AS lastaccess, {$ctxfields}
                  FROM {user} u
             LEFT JOIN {user_lastaccess} ul ON ul.userid = u.id AND ul.courseid = :{$courseparam}
             LEFT JOIN {context} ctx ON ctx.instanceid = u.id AND ctx.contextlevel = :{$ctxparam}
                       {$userfields->joins}
                 WHERE u.id {$insql}";
        $params = array_merge($userfields->params, $inparams, [$courseparam => $this->course->id, $ctxparam => CONTEXT_USER]);
        $records = $DB->get_records_sql($sql, $params);

        $users = [];
        foreach ($userids as $userid) {
            if (!isset($records[$userid])) {
                continue;
            }
            $user = $records[$userid];
            \context_helper::preload_from_record($user);
            // The preload leaves the columns in place when the user context does not exist.
            unset($user->ctxid, $user->ctxpath, $user->ctxdepth, $user->ctxlevel, $user->ctxinstance, $user->ctxlocked);
            $user->lastaccess = (int) $user->lastaccess;
            $users[$userid] = $user;
        }
        return $users;
    }

    /**
     * Returns a recordset of the ids (field `id`) of every matching user, in display order, for exports.
     *
     * @param array $sortcolumns column => SORT_ASC|SORT_DESC (as flexible_table::get_sort_columns()).
     * @return \moodle_recordset The caller must close it.
     */
    public function get_userids_recordset(array $sortcolumns): \moodle_recordset {
        global $DB;

        $orderby = $this->get_order_by($sortcolumns);
        ['from' => $from, 'where' => $where, 'params' => $params] = $this->get_query_sql($this->needs_lastaccess_join($orderby));
        if ($this->filter->is_notingroup()) {
            $where = '1 = 0';
        }
        return $DB->get_recordset_sql("SELECT u.id FROM {$from} WHERE {$where} ORDER BY {$orderby}", $params);
    }

    /**
     * Returns the ids of the first matching users using the default sort (for "select all N matching users").
     *
     * @param int $limit Maximum number of ids to return.
     * @return int[]
     */
    public function get_matching_userids(int $limit): array {
        return $this->get_page_userids([], 0, $limit);
    }

    /**
     * Returns the column keys the report can be sorted by.
     *
     * These are fullname, firstname, lastname, the visible identity fields stored in the user table and the
     * course last access (unless hidden). Custom profile fields are not sortable on purpose: sorting by them
     * would require joining their data for every user of the course.
     *
     * @param \context_course $context The course context.
     * @return string[]
     */
    public static function get_sortable_columns(\context_course $context): array {
        $columns = ['fullname', 'firstname', 'lastname'];
        foreach (fields::get_identity_fields($context) as $field) {
            if (fields::match_custom_field($field) === '' && preg_match('/^[a-z0-9_]+$/', $field)) {
                $columns[] = $field;
            }
        }
        if (!filter::is_hidden_user_field('lastaccess', $context)) {
            $columns[] = 'lastaccess';
        }
        return array_values(array_unique($columns));
    }

    /**
     * Whether a query ordered by the given ORDER BY clause needs the last access join.
     *
     * @param string $orderby ORDER BY clause built by {@see self::get_order_by()}.
     * @return bool True when the last access filter is active or the clause sorts by last access.
     */
    private function needs_lastaccess_join(string $orderby): bool {
        return $this->filter->get_accesssince() !== 0 || str_contains($orderby, 'ul.');
    }

    /**
     * Returns the FROM, WHERE and params of a query, with the last access join only when requested.
     *
     * The join parameter is added only together with the join.
     *
     * @param bool $withlastaccess Whether to join {user_lastaccess} as ul.
     * @return array ['from' => string, 'where' => string, 'params' => array]
     */
    private function get_query_sql(bool $withlastaccess): array {
        $base = $this->get_base_sql();
        $from = $base['from'];
        $params = $base['params'];
        if ($withlastaccess) {
            $from .= $base['join'];
            $params += $base['joinparams'];
        }
        return ['from' => $from, 'where' => $base['where'], 'params' => $params];
    }

    /**
     * Builds (once) the FROM, last access JOIN, WHERE and params shared by every query.
     *
     * @return array ['from' => string, 'join' => string, 'joinparams' => array, 'where' => string, 'params' => array]
     */
    private function get_base_sql(): array {
        global $CFG;

        if ($this->basesql !== null) {
            return $this->basesql;
        }

        $params = [];
        $joinparams = [];
        $joincourseparam = $this->add_param($joinparams, $this->course->id);
        $join = "\n LEFT JOIN {user_lastaccess} ul ON ul.userid = u.id AND ul.courseid = :{$joincourseparam}";

        $guestparam = $this->add_param($params, (int) $CFG->siteguest);
        $courseparam = $this->add_param($params, $this->course->id);
        $enrolledsql = "SELECT ue.userid
                          FROM {user_enrolments} ue
                          JOIN {enrol} e ON e.id = ue.enrolid
                         WHERE e.courseid = :{$courseparam}";
        if ($this->filter->is_forced_active()) {
            $enrolledsql .= ' AND ' . $this->get_active_condition('ue', 'e', $params);
        }
        $wheres = [
            'u.deleted = 0',
            "u.id <> :{$guestparam}",
            "u.id IN ({$enrolledsql})",
        ];

        $conditions = [
            $this->get_enrolment_condition($params),
            $this->get_role_condition($params),
            $this->get_group_condition($params),
            $this->get_accesssince_condition($params),
            $this->get_search_condition($params),
        ];
        foreach ($conditions as $condition) {
            if ($condition !== '') {
                $wheres[] = $condition;
            }
        }
        if ($this->filter->is_notingroup()) {
            $wheres[] = '1 = 0';
        }

        $this->basesql = [
            'from' => '{user} u',
            'join' => $join,
            'joinparams' => $joinparams,
            'where' => implode("\n AND ", $wheres),
            'params' => $params,
        ];
        return $this->basesql;
    }

    /**
     * Returns the condition matching an active user enrolment (same as core get_status_sql()).
     *
     * @param string $uealias Alias of {user_enrolments}.
     * @param string $ealias Alias of {enrol}.
     * @param array $params Params, updated.
     * @return string
     */
    private function get_active_condition(string $uealias, string $ealias, array &$params): string {
        // Round 'now' to help DB caching.
        $now = (int) round(time(), -2);
        $active = $this->add_param($params, ENROL_USER_ACTIVE);
        $enabled = $this->add_param($params, ENROL_INSTANCE_ENABLED);
        $now1 = $this->add_param($params, $now);
        $now2 = $this->add_param($params, $now);
        return "({$uealias}.status = :{$active} AND {$ealias}.status = :{$enabled}
                 AND {$uealias}.timestart < :{$now1}
                 AND ({$uealias}.timeend = 0 OR {$uealias}.timeend > :{$now2}))";
    }

    /**
     * Returns the enrolment status / method condition.
     *
     * When both are set they must match the same enrolment (e.g. "Manual enrolments" + "Suspended").
     *
     * @param array $params Params, updated.
     * @return string Empty when not filtering.
     */
    private function get_enrolment_condition(array &$params): string {
        $status = $this->filter->get_status();
        $enrolid = $this->filter->get_enrolid();
        if ($status === filter::STATUS_ANY && $enrolid === 0) {
            return '';
        }

        $courseparam = $this->add_param($params, $this->course->id);
        $conditions = ["fe.courseid = :{$courseparam}"];
        if ($enrolid !== 0) {
            $conditions[] = 'fe.id = :' . $this->add_param($params, $enrolid);
        }
        if ($status === filter::STATUS_ACTIVE) {
            $conditions[] = $this->get_active_condition('fue', 'fe', $params);
        } else if ($status === filter::STATUS_SUSPENDED) {
            $conditions[] = 'fue.status = :' . $this->add_param($params, ENROL_USER_SUSPENDED);
        } else if ($status === filter::STATUS_NOTCURRENT) {
            // Same classification as the status column: active enrolment that is disabled, not started or ended.
            $now = (int) round(time(), -2);
            $active = $this->add_param($params, ENROL_USER_ACTIVE);
            $enabled = $this->add_param($params, ENROL_INSTANCE_ENABLED);
            $now1 = $this->add_param($params, $now);
            $now2 = $this->add_param($params, $now);
            $conditions[] = "fue.status = :{$active}
                             AND (fe.status <> :{$enabled}
                                  OR fue.timestart >= :{$now1}
                                  OR (fue.timeend > 0 AND fue.timeend <= :{$now2}))";
        }

        return 'u.id IN (SELECT fue.userid
                           FROM {user_enrolments} fue
                           JOIN {enrol} fe ON fe.id = fue.enrolid
                          WHERE ' . implode(' AND ', $conditions) . ')';
    }

    /**
     * Returns the role condition, considering role assignments in the course and its parent contexts.
     *
     * @param array $params Params, updated.
     * @return string Empty when not filtering.
     */
    private function get_role_condition(array &$params): string {
        global $DB;

        $roleid = $this->filter->get_roleid();
        if ($roleid === 0) {
            return '';
        }

        $contextids = $this->context->get_parent_context_ids(true);
        [$ctxsql, $ctxparams] = $DB->get_in_or_equal($contextids, SQL_PARAMS_NAMED, $this->next_param_name() . '_');
        $params = array_merge($params, $ctxparams);

        if ($roleid === filter::ROLE_NONE) {
            return "u.id NOT IN (SELECT ra.userid FROM {role_assignments} ra WHERE ra.contextid {$ctxsql})";
        }
        $roleparam = $this->add_param($params, $roleid);
        return "u.id IN (SELECT ra.userid
                           FROM {role_assignments} ra
                          WHERE ra.roleid = :{$roleparam} AND ra.contextid {$ctxsql})";
    }

    /**
     * Returns the group condition (user filter plus separate groups restriction), respecting group visibility.
     *
     * @param array $params Params, updated.
     * @return string Empty when not filtering.
     */
    private function get_group_condition(array &$params): string {
        global $DB;

        $groupid = $this->filter->get_groupid();
        $allowed = $this->filter->get_allowed_groupids();

        if ($groupid === USERSWITHOUTGROUP) {
            $courseparam = $this->add_param($params, $this->course->id);
            $visibility = $this->get_member_visibility_condition($params);
            return "u.id NOT IN (SELECT gm.userid
                                   FROM {groups_members} gm
                                   JOIN {groups} g ON g.id = gm.groupid
                                  WHERE g.courseid = :{$courseparam}{$visibility})";
        }

        if ($groupid > 0) {
            // A chosen group is always one of the allowed groups once normalised.
            $groupids = [$groupid];
        } else if ($allowed !== null && !empty($allowed)) {
            $groupids = $allowed;
        } else {
            return '';
        }

        [$groupsql, $groupparams] = $DB->get_in_or_equal($groupids, SQL_PARAMS_NAMED, $this->next_param_name() . '_');
        $params = array_merge($params, $groupparams);
        $visibility = $this->get_member_visibility_condition($params);
        return "u.id IN (SELECT gm.userid
                           FROM {groups_members} gm
                           JOIN {groups} g ON g.id = gm.groupid
                          WHERE gm.groupid {$groupsql}{$visibility})";
    }

    /**
     * Returns the group membership visibility condition (as core_group\visibility::sql_member_visibility_where()).
     *
     * It refers to the aliases g ({groups}) and gm ({groups_members}) and is empty when the current user can see
     * every group of the course.
     *
     * @param array $params Params, updated.
     * @return string Empty or a condition starting with " AND ".
     */
    private function get_member_visibility_condition(array &$params): string {
        global $USER;

        if (\core_group\visibility::can_view_all_groups($this->course->id)) {
            return '';
        }
        $all = $this->add_param($params, GROUPS_VISIBILITY_ALL);
        $members = $this->add_param($params, GROUPS_VISIBILITY_MEMBERS);
        $me = $this->add_param($params, $USER->id);
        $own = $this->add_param($params, GROUPS_VISIBILITY_OWN);
        $me2 = $this->add_param($params, $USER->id);
        return " AND (g.visibility = :{$all}
                      OR (g.visibility = :{$members}
                          AND gm.groupid IN (SELECT gmv.groupid FROM {groups_members} gmv WHERE gmv.userid = :{$me}))
                      OR (g.visibility = :{$own} AND gm.userid = :{$me2}))";
    }

    /**
     * Returns the last access condition (same semantics as core user_get_course_lastaccess_sql()).
     *
     * @param array $params Params, updated.
     * @return string Empty when not filtering.
     */
    private function get_accesssince_condition(array &$params): string {
        $accesssince = $this->filter->get_accesssince();
        if ($accesssince === 0) {
            return '';
        }
        if ($accesssince === filter::ACCESS_NEVER) {
            return '(ul.timeaccess IS NULL OR ul.timeaccess = 0)';
        }
        // Midnight based, like the core filter, so the value (and query) is stable during the day.
        $cutoff = (int) strtotime("-{$accesssince} days", usergetmidnight(time()));
        $cutoffparam = $this->add_param($params, $cutoff);
        return "(ul.timeaccess IS NULL OR ul.timeaccess < :{$cutoffparam})";
    }

    /**
     * Returns the text search condition, on a single column (or a single profile field).
     *
     * @param array $params Params, updated.
     * @return string Empty when not searching.
     */
    private function get_search_condition(array &$params): string {
        global $CFG, $DB;

        $search = $this->filter->get_search();
        if ($search === '') {
            return '';
        }
        $searchparam = $this->add_param($params, '%' . $DB->sql_like_escape($search) . '%');
        $field = $this->filter->get_searchfield();

        if ($field === filter::FIELD_FULLNAME) {
            [$fullname, $fullnameparams] = fields::get_sql_fullname(
                'u',
                has_capability('moodle/site:viewfullnames', $this->context)
            );
            $params = array_merge($params, $fullnameparams);
            return $DB->sql_like($fullname, ':' . $searchparam, false, false);
        }

        // Never trust the field name: it must be a visible identity field.
        if (!in_array($field, fields::get_identity_fields($this->context), true)) {
            return '';
        }

        $shortname = fields::match_custom_field($field);
        if ($shortname !== '') {
            require_once($CFG->dirroot . '/user/profile/lib.php');
            $profilefield = profile_get_custom_field_data_by_shortname($shortname, false);
            if ($profilefield === null) {
                return '1 = 0';
            }
            $fieldparam = $this->add_param($params, (int) $profilefield->id);
            return "u.id IN (SELECT uid.userid
                               FROM {user_info_data} uid
                              WHERE uid.fieldid = :{$fieldparam}
                                AND " . $DB->sql_like('uid.data', ':' . $searchparam, false, false) . ')';
        }

        if (!preg_match('/^[a-z0-9_]+$/', $field)) {
            return '';
        }
        return $DB->sql_like('u.' . $field, ':' . $searchparam, false, false);
    }

    /**
     * Returns the ORDER BY clause from whitelisted columns, always ending with u.id as tie-break.
     *
     * @param array $sortcolumns column => SORT_ASC|SORT_DESC.
     * @return string
     */
    private function get_order_by(array $sortcolumns): string {
        $sortable = self::get_sortable_columns($this->context);
        $orderby = [];
        $used = [];
        foreach ($sortcolumns as $column => $direction) {
            if (!is_string($column) || !in_array($column, $sortable, true)) {
                continue;
            }
            $dir = ((int) $direction === SORT_DESC) ? 'DESC' : 'ASC';
            foreach ($this->get_sort_expressions($column) as $expression) {
                if (isset($used[$expression])) {
                    continue;
                }
                $used[$expression] = true;
                $orderby[] = "{$expression} {$dir}";
            }
        }
        if (empty($orderby)) {
            $orderby = ['u.lastname ASC', 'u.firstname ASC'];
        }
        $orderby[] = 'u.id ASC';
        return implode(', ', $orderby);
    }

    /**
     * Returns the SQL expressions used to sort by a whitelisted column.
     *
     * @param string $column Column key.
     * @return string[]
     */
    private function get_sort_expressions(string $column): array {
        switch ($column) {
            case 'fullname':
                return array_map(static fn(string $name): string => 'u.' . $name, self::get_fullname_sort_fields());
            case 'lastaccess':
                return ['COALESCE(ul.timeaccess, 0)'];
            default:
                return ['u.' . $column];
        }
    }

    /**
     * Returns firstname/lastname in the order they appear in the configured full name format.
     *
     * @return string[]
     */
    private static function get_fullname_sort_fields(): array {
        $order = array_values(order_in_string(['firstname', 'lastname'], \core_user::get_dummy_fullname()));
        foreach (['lastname', 'firstname'] as $name) {
            if (!in_array($name, $order, true)) {
                $order[] = $name;
            }
        }
        return $order;
    }

    /**
     * Adds a parameter with a unique name.
     *
     * @param array $params Params, updated.
     * @param mixed $value Parameter value.
     * @return string The parameter name (without colon).
     */
    private function add_param(array &$params, $value): string {
        $name = $this->next_param_name();
        $params[$name] = $value;
        return $name;
    }

    /**
     * Returns a new unique parameter name (or prefix).
     *
     * @return string
     */
    private function next_param_name(): string {
        $this->paramcounter++;
        return self::PARAM_PREFIX . $this->paramcounter;
    }
}
